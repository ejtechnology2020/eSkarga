-- V12: słownik sędziów (S-24, ADR 0027) – login z ID-users, nazwa do pism, funkcja (PREZES, WICEPREZES, SEDZIA), kadencja.
-- Źródło listy sędziów do wyznaczenia (S-17) i składów rozpoznających zażalenia (S-18); wpisy wycofywane, nie usuwane.
CREATE TABLE judge (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       VARCHAR(100) NOT NULL,
  display_name  VARCHAR(200) NOT NULL,
  function_code VARCHAR(20)  NOT NULL,
  term_from     DATE         NOT NULL,
  term_to       DATE,
  active        BOOLEAN      NOT NULL DEFAULT TRUE,
  created_by    VARCHAR(120) NOT NULL,
  created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
  updated_by    VARCHAR(120),
  updated_at    TIMESTAMP WITH TIME ZONE,
  CONSTRAINT uq_judge_user UNIQUE (user_id)
);
CREATE INDEX ix_judge_active ON judge (active, term_from, term_to);
