-- licznik dziennika wpływu, rejestry pomocnicze (pisma ogólne, publikacja, archiwum), kategorie archiwalne (ADR 0012).

CREATE TABLE incoming_counter (
  year        INTEGER NOT NULL PRIMARY KEY,
  last_value  INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE court (
  id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code      VARCHAR(30) NOT NULL UNIQUE,
  name      VARCHAR(300) NOT NULL,
  active    BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE authority (
  id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code      VARCHAR(30) NOT NULL UNIQUE,
  name      VARCHAR(300) NOT NULL,
  active    BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE letter_type (
  id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code      VARCHAR(30) NOT NULL UNIQUE,
  name      VARCHAR(300) NOT NULL,
  active    BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE review_standard (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code        VARCHAR(30) NOT NULL UNIQUE,
  provision   VARCHAR(200) NOT NULL,
  description VARCHAR(400),
  active      BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE review_subject (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_file_id  BIGINT NOT NULL REFERENCES case_file (id),
  act           VARCHAR(400) NOT NULL,
  unit          VARCHAR(120),
  standard      VARCHAR(400)
);

CREATE TABLE case_assignment (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_file_id  BIGINT NOT NULL REFERENCES case_file (id),
  user_id       VARCHAR(120) NOT NULL,
  role          VARCHAR(20) NOT NULL,                  -- JUDGE, TEAM, CLERK
  assigned_on   DATE NOT NULL,
  released_on   DATE,
  CONSTRAINT uq_case_assignment UNIQUE (case_file_id, user_id, role, assigned_on)
);

CREATE TABLE internal_note (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_file_id  BIGINT NOT NULL REFERENCES case_file (id),
  author_user_id VARCHAR(120) NOT NULL,
  title         VARCHAR(300) NOT NULL,
  body          TEXT NOT NULL,
  created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE highlight (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id   BIGINT NOT NULL REFERENCES case_document (id),
  author_user_id VARCHAR(120) NOT NULL,
  page_no       INTEGER NOT NULL,
  geometry_json VARCHAR(4000) NOT NULL,                -- współrzędne jako JSON, rysowane jako nakładka
  comment_text  VARCHAR(2000),
  created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE general_letter (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  letter_id     BIGINT NOT NULL REFERENCES incoming_letter (id),
  subject       VARCHAR(600),
  reply_due_on  DATE,
  replied_on    DATE,
  reply_document_id BIGINT REFERENCES case_document (id),
  template_code VARCHAR(60)
);

CREATE TABLE publication (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id   BIGINT NOT NULL REFERENCES case_document (id),
  anonymised_key VARCHAR(400),
  replacements  INTEGER NOT NULL DEFAULT 0,
  approved_by   VARCHAR(120),
  approved_at   TIMESTAMP WITH TIME ZONE,
  published_at  TIMESTAMP WITH TIME ZONE,
  status        VARCHAR(20) NOT NULL                   -- OCZEKUJE, ZATWIERDZONA, OPUBLIKOWANA, POPRAWKA
);

CREATE TABLE archive_category (
  closing_mode   VARCHAR(60) PRIMARY KEY,              -- sposób zakończenia sprawy
  category       VARCHAR(10) NOT NULL,                 -- A, B10, B25, BE50
  retention_years INTEGER,                             -- NULL = wieczyście
  updated_by     VARCHAR(120),
  updated_at     TIMESTAMP WITH TIME ZONE
);
