CREATE TABLE archive_transfer (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  transfer_no   VARCHAR(30) NOT NULL UNIQUE,            -- 14/2026
  case_file_id  BIGINT NOT NULL REFERENCES case_file (id),
  category      VARCHAR(10) NOT NULL,
  retention_until INTEGER,
  pages         INTEGER NOT NULL,
  package_key   VARCHAR(400),
  package_sha256 CHAR(64),
  transferred_by VARCHAR(120) NOT NULL,
  transferred_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE INDEX ix_case_assignment_user ON case_assignment (user_id, released_on);
CREATE INDEX ix_internal_note_case ON internal_note (case_file_id);
CREATE INDEX ix_highlight_doc ON highlight (document_id, page_no);
