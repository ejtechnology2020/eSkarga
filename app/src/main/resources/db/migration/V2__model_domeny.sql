-- V2: model domeny (analiza §8.1, T-010). Wpisy repertorium są wersjonowane: korekta dodaje wiersz
-- case_file_version z wyższym numerem wersji (UC-22), nigdy UPDATE.

CREATE TABLE incoming_letter (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  register_no      VARCHAR(20)  NOT NULL UNIQUE,          -- DW 2026/04812
  received_at      TIMESTAMP WITH TIME ZONE NOT NULL,     -- data i godzina wpływu
  filed_on         DATE,                                  -- data wniesienia (stempel / UPO), FR-02
  filed_on_uncertain BOOLEAN NOT NULL DEFAULT FALSE,
  channel          VARCHAR(20)  NOT NULL,                 -- OSOBISCIE, POCZTA, EPUAP, EDORECZENIA
  sender           VARCHAR(400) NOT NULL,
  attachments      INTEGER NOT NULL DEFAULT 0,
  copies           INTEGER NOT NULL DEFAULT 0,
  classified       BOOLEAN NOT NULL DEFAULT FALSE,        -- dokument z klauzulą: tylko metadane (NFR-06)
  qualification    VARCHAR(30),                           -- LetterQualification
  case_file_id     BIGINT,
  created_by       VARCHAR(120) NOT NULL,
  created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE case_file (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  docket_symbol    VARCHAR(3)  NOT NULL,
  docket_number    INTEGER     NOT NULL,
  docket_year      INTEGER     NOT NULL,
  entered_on       DATE        NOT NULL,
  process_instance_id VARCHAR(64),
  created_by       VARCHAR(120) NOT NULL,
  created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
  CONSTRAINT uq_case_file_docket UNIQUE (docket_symbol, docket_number, docket_year)
);
ALTER TABLE incoming_letter ADD CONSTRAINT fk_letter_case FOREIGN KEY (case_file_id) REFERENCES case_file (id);

-- Wersjonowany wpis repertorium: status, strony, przedmiot, sędzia, flagi. Aktualna = najwyższa version.
CREATE TABLE case_file_version (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_file_id     BIGINT NOT NULL REFERENCES case_file (id),
  version          INTEGER NOT NULL,
  status           VARCHAR(40) NOT NULL,
  judge_user_id    VARCHAR(120),
  flag_urgent      BOOLEAN NOT NULL DEFAULT FALSE,       -- art. 79
  flag_anonymise   BOOLEAN NOT NULL DEFAULT FALSE,       -- art. 80
  flag_suspended   BOOLEAN NOT NULL DEFAULT FALSE,       -- art. 78
  review_subject   VARCHAR(1000),
  review_standard  VARCHAR(1000),
  closed_on        DATE,
  closing_mode     VARCHAR(60),
  related_docket   VARCHAR(20),                           -- SK 41/26 po nadaniu biegu
  justification    VARCHAR(2000),                         -- uzasadnienie korekty (version > 1)
  approved_by      VARCHAR(120),                          -- kierownik akceptujący korektę
  created_by       VARCHAR(120) NOT NULL,
  created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
  CONSTRAINT uq_case_file_version UNIQUE (case_file_id, version)
);

CREATE TABLE party (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_file_id     BIGINT NOT NULL REFERENCES case_file (id),
  role             VARCHAR(30) NOT NULL,                  -- SKARZACY, WNIOSKODAWCA, PELNOMOCNIK, UCZESTNIK
  display_name     VARCHAR(400) NOT NULL,
  delivery_address VARCHAR(600),
  e_delivery_address VARCHAR(120),
  created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE power_of_attorney (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  party_id         BIGINT NOT NULL REFERENCES party (id),
  kind             VARCHAR(30) NOT NULL,                  -- SZCZEGOLNE, Z_URZEDU, OGOLNE
  profession       VARCHAR(30),                           -- ADWOKAT, RADCA_PRAWNY
  registry_no      VARCHAR(60),
  granted_on       DATE,
  scope            VARCHAR(400)
);

CREATE TABLE final_ruling (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_file_id     BIGINT NOT NULL REFERENCES case_file (id),
  authority        VARCHAR(400) NOT NULL,
  ruling_ref       VARCHAR(120),
  issued_on        DATE,
  delivered_on     DATE,                                  -- początek terminu z art. 77
  extraordinary_remedy BOOLEAN NOT NULL DEFAULT FALSE     -- art. 78
);

CREATE TABLE case_document (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_file_id     BIGINT NOT NULL REFERENCES case_file (id),
  volume_no        INTEGER NOT NULL DEFAULT 1,
  page_from        INTEGER,
  page_to          INTEGER,
  title            VARCHAR(400) NOT NULL,
  kind             VARCHAR(30) NOT NULL,                  -- DocumentKind
  document_date    DATE,
  storage_key      VARCHAR(400),                          -- klucz w repozytorium S3; NULL dla niejawnych
  sha256           CHAR(64),
  version          INTEGER NOT NULL DEFAULT 1,
  classified       BOOLEAN NOT NULL DEFAULT FALSE,
  internal_note    BOOLEAN NOT NULL DEFAULT FALSE,        -- notatka wewnętrzna zespołu sędziego (FR-24)
  anonymised_key   VARCHAR(400),
  signature_status VARCHAR(30),
  template_version_id BIGINT,
  created_by       VARCHAR(120) NOT NULL,
  created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE procedural_act (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_file_id     BIGINT NOT NULL REFERENCES case_file (id),
  kind             VARCHAR(40) NOT NULL,                  -- ZARZADZENIE, POSTANOWIENIE, NOTATKA, PRZEKAZANIE
  subtype          VARCHAR(60),                           -- np. ODMOWA_ART_61_4_PKT_1
  acted_on         TIMESTAMP WITH TIME ZONE NOT NULL,
  author_user_id   VARCHAR(120) NOT NULL,
  panel_user_ids   VARCHAR(400),
  legal_basis      VARCHAR(200),
  document_id      BIGINT REFERENCES case_document (id),
  status           VARCHAR(30) NOT NULL                   -- PROJEKT, PODPISANA, WYSLANA
);

CREATE TABLE delivery (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id      BIGINT NOT NULL REFERENCES case_document (id),
  addressee_party_id BIGINT REFERENCES party (id),
  channel          VARCHAR(30) NOT NULL,
  dispatch_no      VARCHAR(80),
  sent_on          DATE,
  delivered_on     DATE,
  method           VARCHAR(20),                           -- DO_RAK, ZASTEPCZE, AWIZO
  idempotency_key  VARCHAR(80) NOT NULL UNIQUE,
  created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE deadline (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_file_id     BIGINT NOT NULL REFERENCES case_file (id),
  delivery_id      BIGINT REFERENCES delivery (id),
  kind             VARCHAR(20) NOT NULL,                  -- BRAKI, ZAZALENIE, ART_77
  starts_on        DATE NOT NULL,
  ends_on          DATE NOT NULL,
  suspended_from   DATE,
  suspended_to     DATE,
  status           VARCHAR(20) NOT NULL,                  -- BIEGNIE, WSTRZYMANY, ZAKONCZONY
  created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE appeal (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_file_id     BIGINT NOT NULL REFERENCES case_file (id),
  filed_on         DATE NOT NULL,
  in_time          BOOLEAN,                               -- ocena pomocnicza
  panel_user_ids   VARCHAR(400),
  session_on       DATE,
  outcome          VARCHAR(40),
  created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE access_request (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_file_id     BIGINT NOT NULL REFERENCES case_file (id),
  requester        VARCHAR(400) NOT NULL,
  participant      BOOLEAN NOT NULL,                      -- uczestnik czy osoba trzecia (BR-09)
  scope            VARCHAR(600),
  fee_pln          NUMERIC(10,2),
  reading_room_at  TIMESTAMP WITH TIME ZONE,
  anonymised_ready BOOLEAN NOT NULL DEFAULT FALSE,
  created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE letter_template (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code             VARCHAR(60)  NOT NULL,
  name             VARCHAR(200) NOT NULL,
  version          INTEGER NOT NULL,
  status           VARCHAR(20) NOT NULL,                  -- PROJEKT, AKTYWNA, WYCOFANA
  source_xhtml     TEXT NOT NULL,
  author_user_id   VARCHAR(120) NOT NULL,
  approved_by      VARCHAR(120),
  created_at       TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
  CONSTRAINT uq_letter_template UNIQUE (code, version)
);
ALTER TABLE case_document ADD CONSTRAINT fk_doc_template FOREIGN KEY (template_version_id) REFERENCES letter_template (id);

CREATE INDEX ix_case_file_version_case ON case_file_version (case_file_id, version DESC);
CREATE INDEX ix_case_document_case ON case_document (case_file_id, volume_no, page_from);
CREATE INDEX ix_deadline_case ON deadline (case_file_id, status);
