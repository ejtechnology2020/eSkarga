-- V7: osoby znane eSkardze (S-22, T-004): login, nazwa i role z tokenu ID-users zapamiętane przy logowaniu, ostatnie logowanie.
-- Konta i role prowadzi ID-users (D4); to jedynie rejestr do listy użytkowników administratora.
CREATE TABLE app_user_seen (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  login            VARCHAR(100) NOT NULL UNIQUE,
  display_name     VARCHAR(200),
  roles            VARCHAR(400) NOT NULL,                 -- TK_REFERENT,TK_KIEROWNIK
  first_seen_at    TIMESTAMP WITH TIME ZONE NOT NULL,
  last_login_at    TIMESTAMP WITH TIME ZONE NOT NULL,
  login_count      INTEGER NOT NULL DEFAULT 1
);
