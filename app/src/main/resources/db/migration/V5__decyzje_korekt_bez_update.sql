-- V5 (NFR-01, UC-22): decyzja o korekcie jako osobny, dopisywany wiersz – tabela case_file_version nie jest już aktualizowana.
ALTER TABLE case_file_version DROP COLUMN correction_status;
ALTER TABLE case_file_version DROP COLUMN approved_by;
ALTER TABLE case_file_version ADD COLUMN is_correction BOOLEAN NOT NULL DEFAULT FALSE;   -- wersja z wniosku o korektę (czeka na decyzję)

CREATE TABLE correction_decision (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  version_id  BIGINT NOT NULL REFERENCES case_file_version (id),
  decision    VARCHAR(20) NOT NULL,                    -- ZATWIERDZONA, ODRZUCONA
  decided_by  VARCHAR(120) NOT NULL,
  decided_at  TIMESTAMP WITH TIME ZONE NOT NULL,
  remarks     VARCHAR(2000)
);
CREATE INDEX ix_correction_decision_version ON correction_decision (version_id);
