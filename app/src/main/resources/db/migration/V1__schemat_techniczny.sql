-- V1: tabele techniczne schematu repertorium (T-003). Rola aplikacji ma tylko INSERT/SELECT na tabelach
-- repertorium (NFR-01); UPDATE jest dopuszczony wyłącznie na docket_counter (licznik sygnatur, BR-01).

CREATE TABLE docket_counter (
  symbol      VARCHAR(3)  NOT NULL,
  year        INTEGER     NOT NULL,
  last_value  INTEGER     NOT NULL DEFAULT 0,
  CONSTRAINT pk_docket_counter PRIMARY KEY (symbol, year),
  CONSTRAINT ck_docket_symbol CHECK (symbol IN ('Ts', 'Tw'))
);

CREATE TABLE audit_event (
  id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  occurred_at  TIMESTAMP WITH TIME ZONE NOT NULL,
  user_id      VARCHAR(120) NOT NULL,
  user_role    VARCHAR(60),
  action       VARCHAR(80)  NOT NULL,
  object_ref   VARCHAR(200),
  case_ref     VARCHAR(20),
  remote_addr  VARCHAR(45),
  prev_hash    CHAR(64) NOT NULL,
  hash         CHAR(64) NOT NULL
);
CREATE INDEX ix_audit_event_case ON audit_event (case_ref, occurred_at);
CREATE INDEX ix_audit_event_user ON audit_event (user_id, occurred_at);

-- Dni wolne w Trybunale (poza świętami ustawowymi liczonymi w kodzie) – kalendarz terminów (BR-02)
CREATE TABLE holiday (
  day          DATE PRIMARY KEY,
  description  VARCHAR(200) NOT NULL,
  created_by   VARCHAR(120) NOT NULL,
  created_at   TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

-- Upoważnienia (BR-10, FR-36): osoba, funkcja, od–do, akt podstawowy
CREATE TABLE delegation (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       VARCHAR(120) NOT NULL,
  function_code VARCHAR(60)  NOT NULL,
  valid_from    DATE NOT NULL,
  valid_to      DATE NOT NULL,
  basis_doc_ref VARCHAR(200),
  revoked_at    TIMESTAMP WITH TIME ZONE,
  created_by    VARCHAR(120) NOT NULL,
  created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
  CONSTRAINT ck_delegation_period CHECK (valid_to >= valid_from)
);
CREATE INDEX ix_delegation_user ON delegation (user_id, function_code, valid_from, valid_to);
