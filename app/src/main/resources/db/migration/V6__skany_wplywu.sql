-- V6: skany pism dołączane przy rejestracji wpływu (S-03, FR-03, T-055): plik w S3 (D5), metadane i SHA-256 w bazie.
CREATE TABLE incoming_scan (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  letter_id        BIGINT NOT NULL REFERENCES incoming_letter (id),
  file_name        VARCHAR(255) NOT NULL,
  content_type     VARCHAR(100) NOT NULL,                 -- application/pdf, image/tiff
  size_bytes       BIGINT NOT NULL,
  sha256           CHAR(64) NOT NULL,
  storage_key      VARCHAR(400) NOT NULL,                 -- klucz obiektu w repozytorium S3
  uploaded_by      VARCHAR(100) NOT NULL,
  uploaded_at      TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_incoming_scan_letter ON incoming_scan (letter_id);
