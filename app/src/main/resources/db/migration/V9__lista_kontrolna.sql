-- Lista kontrolna wymogów formalnych (UC-06, FR-11, S-14): ocena każdego wymogu z tabeli decyzyjnej Dec_WymogiFormalne.
-- Tabela tylko dopisywana (NFR-01): każda zmiana oceny to nowy wiersz, obowiązuje najnowszy dla (sprawa, kod wymogu).
CREATE TABLE checklist_entry (
  id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_file_id     BIGINT NOT NULL REFERENCES case_file (id),
  requirement_code VARCHAR(60) NOT NULL,
  state            VARCHAR(20) NOT NULL,                 -- SPELNIONY, BRAK, DO_SPRAWDZENIA
  note             VARCHAR(500),
  page_ref         VARCHAR(40),
  decided_by       VARCHAR(120) NOT NULL,
  decided_at       TIMESTAMP NOT NULL
);
CREATE INDEX ix_checklist_entry_case ON checklist_entry (case_file_id, requirement_code, id);
